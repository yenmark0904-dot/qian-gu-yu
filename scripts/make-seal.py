"""Generate public/seal/qgy-seal.svg: a 白文 seal reading 千古遇 in Small Seal script.
Glyph outlines come from Sealie Bold v1.2.0 (SIL OFL 1.1, https://github.com/iebb/sealie),
Small Seal codepoints from Unicode 18 SealSources.txt (kSEAL_MCJK): 千 U+3D680, 古 U+3D67B, 遇 U+3D4FB.
Layout (read right column top→bottom, then left): right column 千 / 古, left column 遇.
usage: python3 scripts/make-seal.py /path/to/Sealie-Bold.ttf"""
import sys
from fontTools.ttLib import TTFont
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.pens.boundsPen import BoundsPen

font = TTFont(sys.argv[1])
gs = font.getGlyphSet()
cmap = font.getBestCmap()

def glyph_path(cp, box, stretch=1.0):
    """Fit glyph cp into box=(x0,y0,x1,y1) (SVG coords, y down), centred."""
    g = gs[cmap[cp]]
    bp = BoundsPen(gs); g.draw(bp)
    gx0, gy0, gx1, gy1 = bp.bounds
    bw, bh = box[2] - box[0], box[3] - box[1]
    sx = bw / (gx1 - gx0); sy = bh / (gy1 - gy0)
    s = min(sx, sy)
    kx, ky = s, s
    # seal-carving habit: fill the cell; allow a limited non-uniform stretch
    if sx > sy: kx = min(sx, s * stretch)
    else: ky = min(sy, s * stretch)
    w, h = (gx1 - gx0) * kx, (gy1 - gy0) * ky
    ox = box[0] + (bw - w) / 2 - gx0 * kx
    oy = box[1] + (bh - h) / 2 + gy1 * ky
    sp = SVGPathPen(gs, ntos=lambda v: ("%.1f" % v).rstrip("0").rstrip("."))
    g.draw(TransformPen(sp, (kx, 0, 0, -ky, ox, oy)))
    return sp.getCommands()

P = 14  # inner margin of the red block
G = 4   # gutter
mid = 50
right = (mid + G / 2, P, 100 - P, None)
d = []
d.append(glyph_path(0x3D680, (right[0], P, right[2], mid - G / 2), 1.7))      # 千
d.append(glyph_path(0x3D67B, (right[0], mid + G / 2, right[2], 100 - P), 1.7))  # 古
d.append(glyph_path(0x3D4FB, (P, P, mid - G / 2, 100 - P), 1.25))             # 遇
paths = " ".join(d)

svg = f"""<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 100 100">
<!-- 千古遇 small-seal 白文 seal. Glyph outlines: Sealie Bold 1.2.0, SIL OFL 1.1 (github.com/iebb/sealie). Generated by scripts/make-seal.py -->
<defs>
<filter id="w" x="-8%" y="-8%" width="116%" height="116%"><feTurbulence type="fractalNoise" baseFrequency=".09" numOctaves="2" seed="7"/><feDisplacementMap in="SourceGraphic" scale="3.2"/></filter>
<mask id="m"><rect width="100" height="100" fill="#fff"/><path fill="#000" stroke="#000" stroke-width=".6" stroke-linejoin="round" d="{paths}"/></mask>
</defs>
<g filter="url(#w)"><rect x="5" y="5" width="90" height="90" rx="5" fill="#b3231a" mask="url(#m)"/></g>
</svg>
"""
open("public/seal/qgy-seal.svg", "w").write(svg)
print(len(svg))
