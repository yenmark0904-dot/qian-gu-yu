export const SPOTLIGHT = CHARACTERS.filter((c) => c.rarity === "SSR");
export const BY_ID = Object.fromEntries(CHARACTERS.map((c) => [c.id, c]));

export type DestinyBook = { title: string; text: string; chapter?: string };

/** Card romance is an if-future with that character, not the main-story ending. */
export const LOVE_FUTURE_NOTE = "與該角色發展為戀人的可能未來";

/** Stories live on `eroticStory`. SSR is 《天命書》; SS and S are 《專屬物語》. */
export function destinyBook(character: Character): DestinyBook | null {
  const erotic = character.eroticStory;
  if (erotic && erotic.trim()) {
    const book: DestinyBook = { title: character.rarity === "SSR" ? "天命書" : "專屬物語", text: erotic };
    if (character.eroticTitle?.trim()) book.chapter = character.eroticTitle;
    return book;
  }
  if (!character.tale) return null;
  const text = character.tale.beats
    .map((beat) => (beat.quote ? `「${beat.text}」` : beat.text))
    .join("\n\n");
  if (!text.trim()) return null;
  return { title: character.tale.title || "天命書", text };
}